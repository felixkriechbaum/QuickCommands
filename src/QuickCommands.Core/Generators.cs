using System.Globalization;
using System.Security.Cryptography;
using System.Text;

namespace QuickCommands.Core;

/// <summary>Builds the text that `qc` prints in the terminal.</summary>
internal static class CommandListing
{
    public const string GeneratedNotice = "Generated by QuickCommands. Do not edit - changes are overwritten on the next save.";

    public static string LanguageLabel(ShellLanguage language) => HelpText.LanguageLabel(language);

    public static IReadOnlyList<string> Lines(IEnumerable<QuickCommand> commands, string title, bool showLanguage, TerminalTexts texts)
    {
        var list = commands
            .OrderBy(c => c.Language)
            .ThenBy(c => c.Name, StringComparer.Ordinal)
            .ToList();

        var lines = new List<string> { title };
        if (list.Count == 0)
        {
            lines.Add("  " + texts.NoCommands);
        }
        else
        {
            var width = Math.Max(8, list.Max(c => c.Name.Length));
            foreach (var c in list)
            {
                var line = "  " + c.Name.PadRight(width);
                if (showLanguage)
                    line += "  " + LanguageLabel(c.Language).PadRight(10);
                line += "  " + SingleLine(c.Description);
                lines.Add(line.TrimEnd());
            }
        }
        lines.Add("");
        lines.Add("  " + texts.Footer);
        return lines;
    }

    /// <summary>`qc name`: the help of every command with that name, across all shells.</summary>
    public static IEnumerable<(string Name, IReadOnlyList<string> Lines)> Details(IEnumerable<QuickCommand> all, TerminalTexts texts) =>
        all.GroupBy(c => c.Name, StringComparer.Ordinal)
            .OrderBy(g => g.Key, StringComparer.Ordinal)
            .Select(g => (g.Key, (IReadOnlyList<string>)g.OrderBy(c => c.Language)
                .SelectMany((c, i) => (i > 0 ? [""] : Array.Empty<string>()).Concat(HelpText.Lines(c, texts, includeLanguage: true)))
                .ToList()));

    public static string SingleLine(string? text) =>
        string.Join(' ', (text ?? "").Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
}

internal static class Stamp
{
    public const string Placeholder = "__QC_STAMP__";

    /// <summary>Replaces the placeholder with a hash of the content – identical output gives an identical stamp.</summary>
    public static (string Text, string Stamp) Apply(string text)
    {
        var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(text)))[..16].ToLowerInvariant();
        return (text.Replace(Placeholder, hash, StringComparison.Ordinal), hash);
    }
}

public static class PowerShellGenerator
{
    /// <summary>
    /// Every command becomes a global function. The body is compiled with [scriptblock]::Create so a syntax
    /// error in one command only produces a warning instead of breaking the whole file.
    /// </summary>
    public static string Generate(IReadOnlyCollection<QuickCommand> all, string scriptPath, string? stampPath = null, GeneratorOptions? options = null) =>
        GenerateWithStamp(all, scriptPath, stampPath, options).Text;

    internal static (string Text, string Stamp) GenerateWithStamp(IReadOnlyCollection<QuickCommand> all, string scriptPath, string? stampPath, GeneratorOptions? options)
    {
        options ??= GeneratorOptions.Default;
        var texts = options.Texts;
        var commands = all.Where(c => c.Language == ShellLanguage.PowerShell).OrderBy(c => c.Name, StringComparer.Ordinal).ToList();
        var sb = new StringBuilder();
        sb.Append("# ").AppendLine(CommandListing.GeneratedNotice);
        sb.AppendLine();
        sb.Append("$global:QcScriptPath = ").AppendLine(Quote(scriptPath));
        sb.Append("$global:QcStampPath = ").AppendLine(Quote(stampPath ?? scriptPath + ".stamp"));
        sb.Append("$global:QcStamp = ").AppendLine(Quote(Stamp.Placeholder));
        sb.Append("$global:QcAutoReload = ").AppendLine(options.AutoReload ? "$true" : "$false");
        sb.AppendLine();
        sb.AppendLine("# Unload the commands of a previous load (qc reload), so deleted commands disappear.");
        sb.AppendLine("if ($global:QcCommandNames) { foreach ($__qcName in $global:QcCommandNames) { Remove-Item -LiteralPath \"Function:\\$__qcName\" -ErrorAction SilentlyContinue } }");
        sb.Append("$global:QcCommandNames = @(").AppendJoin(", ", commands.Select(c => Quote(c.Name))).AppendLine(")");
        sb.AppendLine("$global:QcNameSet = [System.Collections.Generic.HashSet[string]]::new([string[]]$global:QcCommandNames, [System.StringComparer]::OrdinalIgnoreCase)");
        AppendTexts(sb, texts);
        sb.AppendLine("$global:QcSpecs = @{}");
        sb.AppendLine("$global:QcHelp = @{}");
        sb.AppendLine("$global:QcUsage = @{}");
        AppendArray(sb, "$global:QcListing", CommandListing.Lines(commands, string.Format(texts.TitleShell, "powershell"), showLanguage: false, texts));
        AppendArray(sb, "$global:QcListingAll", CommandListing.Lines(all, texts.TitleAll, showLanguage: true, texts));
        sb.AppendLine("$global:QcDetails = @{}");
        foreach (var (name, lines) in CommandListing.Details(all, texts))
            AppendArray(sb, $"$global:QcDetails[{Quote(name)}]", lines);
        sb.AppendLine();
        sb.Append(Runtime);
        sb.AppendLine();

        foreach (var c in commands)
            AppendCommand(sb, c, texts);

        sb.AppendLine("function global:qc {");
        sb.AppendLine("    param([Parameter(Position = 0)][string]$Action, [switch]$a)");
        sb.AppendLine("    if ($Action -eq 'reload') {");
        sb.AppendLine("        . $global:QcScriptPath");
        sb.AppendLine("        Write-Host ($global:QcText.ReloadedCount -f $global:QcCommandNames.Count)");
        sb.AppendLine("        return");
        sb.AppendLine("    }");
        sb.AppendLine("    if ($a -or $Action -eq '-a') { $global:QcListingAll | Write-Host; return }");
        sb.AppendLine("    if (-not $Action) { $global:QcListing | Write-Host; return }");
        sb.AppendLine("    if ($global:QcDetails.ContainsKey($Action)) { $global:QcDetails[$Action] | Write-Host } else { Write-Host ($global:QcText.UnknownCommand + $Action) -ForegroundColor Red }");
        sb.AppendLine("}");
        return Stamp.Apply(sb.ToString().ReplaceLineEndings("\n"));
    }

    /// <summary>
    /// Only the definition of one command (plus the runtime it needs) – used by "Try it" on top of a normal
    /// session, so it must not unload the saved commands.
    /// </summary>
    public static string GenerateSingle(QuickCommand command, TerminalTexts texts)
    {
        var sb = new StringBuilder();
        sb.AppendLine("if (-not $global:QcSpecs) { $global:QcSpecs = @{}; $global:QcHelp = @{}; $global:QcUsage = @{} }");
        AppendTexts(sb, texts);
        sb.Append(Runtime);
        AppendCommand(sb, command, texts);
        return sb.ToString().ReplaceLineEndings("\n");
    }

    private static void AppendTexts(StringBuilder sb, TerminalTexts texts)
    {
        sb.Append("$global:QcText = @{ ")
          .Append("ReloadedCount = ").Append(Quote(texts.ReloadedCount))
          .Append("; MissingArgument = ").Append(Quote(texts.MissingArgument))
          .Append("; MissingValue = ").Append(Quote(texts.MissingValue))
          .Append("; InvalidChoice = ").Append(Quote(texts.InvalidChoice))
          .Append("; UnknownCommand = ").Append(Quote(texts.UnknownCommand))
          .AppendLine(" }");
    }

    private static void AppendCommand(StringBuilder sb, QuickCommand c, TerminalTexts texts)
    {
        sb.Append("# ").AppendLine(c.Name);
        // Aliases win over functions in PowerShell, so an alias with the same name (cd, ls, …) has to go.
        sb.Append("Remove-Item -LiteralPath ").Append(Quote("Alias:\\" + c.Name)).AppendLine(" -Force -ErrorAction SilentlyContinue");

        var body = c.Script.ReplaceLineEndings("\n");
        if (c.HasParameters)
        {
            sb.Append("$global:QcSpecs[").Append(Quote(c.Name)).Append("] = @(")
              .AppendJoin(", ", c.Parameters.Select(Spec)).AppendLine(")");
            AppendArray(sb, $"$global:QcHelp[{Quote(c.Name)}]", HelpText.Lines(c, texts, includeLanguage: false));
            sb.Append("$global:QcUsage[").Append(Quote(c.Name)).Append("] = ")
              .AppendLine(Quote("  " + texts.Usage + " " + HelpText.UsageLine(c)));
            sb.Append("Register-ArgumentCompleter -Native -CommandName ").Append(Quote(c.Name)).AppendLine(" -ScriptBlock $global:QcCompleter");

            // One line in front of the user's script, so line numbers in error messages stay almost the same.
            var prefix = new StringBuilder("$__qcP = __qcParseArgs ").Append(Quote(c.Name)).Append(" $args; if ($__qcP.Stop) { return }; ");
            foreach (var p in c.Parameters)
            {
                var name = ParameterRules.NormalizeName(p.Name);
                prefix.Append('$').Append(name).Append(" = $__qcP.Values[").Append(Quote(name)).Append("]; ");
            }
            prefix.Append("$args = $__qcP.Rest; Remove-Variable __qcP; ");
            body = prefix + body;
        }

        sb.Append("try { ${function:global:").Append(c.Name).Append("} = [scriptblock]::Create(")
          .Append(Quote(body))
          .Append(") } catch { Write-Warning (").Append(Quote(string.Format(texts.CouldNotLoad, c.Name) + " - "))
          .AppendLine(" + $_.Exception.GetBaseException().Message) }");
        sb.AppendLine();
    }

    private static string Spec(CommandParameter p)
    {
        var kind = p.Kind switch { ParameterKind.Switch => "s", ParameterKind.Choice => "c", _ => "t" };
        return "@{ n = " + Quote(ParameterRules.NormalizeName(p.Name)) +
               "; k = '" + kind + "'" +
               "; r = " + (p.Required && p.Kind != ParameterKind.Switch ? "$true" : "$false") +
               "; d = " + Quote(p.EffectiveDefault) +
               "; c = @(" + string.Join(", ", p.Choices.Select(Quote)) + ") }";
    }

    /// <summary>Argument parser, tab completion and auto-reload hooks shared by all commands.</summary>
    private const string Runtime = """
        function global:__qcParseArgs {
            param([string]$Command, [object[]]$Argv)
            $spec = @($global:QcSpecs[$Command])
            $values = @{}
            $set = @{}
            $rest = [System.Collections.Generic.List[object]]::new()
            foreach ($p in $spec) {
                if ($p.k -eq 's') { $values[$p.n] = $false } elseif ($p.d -ne '') { $values[$p.n] = $p.d } else { $values[$p.n] = $null }
            }
            $i = 0
            $literal = $false
            while ($i -lt $Argv.Count) {
                $a = $Argv[$i]
                $i++
                if (-not $literal -and $a -is [string]) {
                    if ($a -eq '--') { $literal = $true; continue }
                    if ($a -eq '-h' -or $a -eq '--help') { $global:QcHelp[$Command] | Write-Host; return @{ Stop = $true } }
                    if ($a -match '^--?([A-Za-z][A-Za-z0-9_]*)(:|=.*)?$') {
                        $flag = $Matches[1]
                        $tail = $Matches[2]
                        $p = $null
                        foreach ($q in $spec) { if ($q.n -eq $flag) { $p = $q; break } }
                        if ($null -eq $p) { $rest.Add($a); continue }
                        if ($p.k -eq 's') { $values[$p.n] = $true; $set[$p.n] = $true; continue }
                        if ($tail -and $tail.StartsWith('=')) { $v = $tail.Substring(1) }
                        elseif ($i -lt $Argv.Count) { $v = $Argv[$i]; $i++ }
                        else {
                            Write-Host ($global:QcText.MissingValue -f $Command, $p.n) -ForegroundColor Red
                            return @{ Stop = $true }
                        }
                        $values[$p.n] = $v
                        $set[$p.n] = $true
                        continue
                    }
                }
                $next = $null
                foreach ($q in $spec) { if ($q.k -ne 's' -and -not $set.ContainsKey($q.n)) { $next = $q; break } }
                if ($null -ne $next) { $values[$next.n] = $a; $set[$next.n] = $true } else { $rest.Add($a) }
            }
            foreach ($p in $spec) {
                if ($p.r -and -not $set.ContainsKey($p.n)) {
                    Write-Host ($global:QcText.MissingArgument -f $Command, $p.n) -ForegroundColor Red
                    Write-Host $global:QcUsage[$Command]
                    return @{ Stop = $true }
                }
                if ($p.k -eq 'c' -and $null -ne $values[$p.n] -and @($p.c) -notcontains [string]$values[$p.n]) {
                    Write-Host ($global:QcText.InvalidChoice -f $Command, $p.n, (@($p.c) -join ', ')) -ForegroundColor Red
                    return @{ Stop = $true }
                }
            }
            return @{ Stop = $false; Values = $values; Rest = $rest.ToArray() }
        }

        $global:QcCompleter = {
            param($wordToComplete, $commandAst, $cursorPosition)
            $spec = @($global:QcSpecs[$commandAst.GetCommandName()])
            $prev = $null
            foreach ($e in $commandAst.CommandElements) { if ($e.Extent.EndOffset -lt $cursorPosition) { $prev = $e.Extent.Text } }
            $results = @()
            if ($prev -match '^--?([A-Za-z][A-Za-z0-9_]*)$') {
                $flag = $Matches[1]
                foreach ($p in $spec) { if ($p.n -eq $flag -and $p.k -eq 'c') { $results = @($p.c | Where-Object { $_ -like "$wordToComplete*" }) } }
            }
            if ($results.Count -eq 0 -and $wordToComplete -like '-*') {
                $results = @(@($spec | ForEach-Object { '--' + $_.n }) + '--help' | Where-Object { $_ -like "$wordToComplete*" })
            }
            foreach ($r in $results) { [System.Management.Automation.CompletionResult]::new($r, $r, 'ParameterValue', $r) }
        }

        function global:__qcCheckReload {
            if (-not $global:QcAutoReload -or -not $global:QcStampPath) { return $false }
            try { $stamp = [System.IO.File]::ReadAllText($global:QcStampPath).Trim() } catch { return $false }
            if ($stamp -eq $global:QcStamp) { return $false }
            . $global:QcScriptPath
            return $true
        }

        # Auto-reload: a saved change is picked up the next time one of the commands (or a new one) is called.
        if (-not $global:QcHooksInstalled) {
            $global:QcHooksInstalled = $true
            $global:QcPrevPreLookup = $ExecutionContext.InvokeCommand.PreCommandLookupAction
            $global:QcPrevNotFound = $ExecutionContext.InvokeCommand.CommandNotFoundAction
            $ExecutionContext.InvokeCommand.PreCommandLookupAction = {
                param($commandName, $eventArgs)
                if ($global:QcNameSet -and $global:QcNameSet.Contains($commandName)) { $null = __qcCheckReload }
                if ($global:QcPrevPreLookup) { & $global:QcPrevPreLookup $commandName $eventArgs }
            }
            $ExecutionContext.InvokeCommand.CommandNotFoundAction = {
                param($commandName, $eventArgs)
                if (__qcCheckReload) {
                    $found = Get-Command -Name $commandName -CommandType Function -ErrorAction SilentlyContinue
                    if ($found) { $eventArgs.Command = $found; $eventArgs.StopSearch = $true; return }
                }
                if ($global:QcPrevNotFound) { & $global:QcPrevNotFound $commandName $eventArgs }
            }
        }

        """;

    private static void AppendArray(StringBuilder sb, string variable, IEnumerable<string> lines)
    {
        sb.Append(variable).AppendLine(" = @(");
        foreach (var line in lines)
            sb.Append("    ").AppendLine(Quote(line));
        sb.AppendLine(")");
    }

    /// <summary>
    /// Single-quoted PowerShell string. PowerShell treats the typographic quotes ‘ ’ ‚ ‛ like ' – all of them
    /// are escaped by doubling.
    /// </summary>
    public static string Quote(string value)
    {
        var sb = new StringBuilder(value.Length + 2).Append('\'');
        foreach (var ch in value)
        {
            if (ch is '\'' or '‘' or '’' or '‚' or '‛')
                sb.Append(ch);
            sb.Append(ch);
        }
        return sb.Append('\'').ToString();
    }
}

public static class ShGenerator
{
    /// <summary>
    /// Every command becomes a shell function (so `cd` works). Each definition goes through `eval`, so a syntax
    /// error in one command does not stop the rest of the file from loading. Works in bash and zsh.
    /// </summary>
    /// <param name="selfReference">How the file refers to itself for `qc reload`, already quoted (e.g. "$HOME/.quickcommands/qc.sh").</param>
    /// <param name="stampReference">The stamp file, quoted the same way.</param>
    public static string Generate(IReadOnlyCollection<QuickCommand> all, string selfReference, string? stampReference = null, GeneratorOptions? options = null) =>
        GenerateWithStamp(all, selfReference, stampReference, options).Text;

    internal static (string Text, string Stamp) GenerateWithStamp(IReadOnlyCollection<QuickCommand> all, string selfReference, string? stampReference, GeneratorOptions? options)
    {
        options ??= GeneratorOptions.Default;
        var texts = options.Texts;
        stampReference ??= selfReference.EndsWith('"') ? selfReference[..^1] + ".stamp\"" : selfReference + ".stamp";
        var commands = all.Where(c => c.Language == ShellLanguage.Sh).OrderBy(c => c.Name, StringComparer.Ordinal).ToList();
        var sb = new StringBuilder();
        sb.Append("# ").AppendLine(CommandListing.GeneratedNotice);
        sb.AppendLine();
        sb.Append("__QC_STAMP=").AppendLine(Quote(Stamp.Placeholder));
        sb.Append("__QC_AUTORELOAD=").AppendLine(options.AutoReload ? "1" : "");
        sb.AppendLine();
        sb.AppendLine("# Unload the commands of a previous load (qc reload), so deleted commands disappear.");
        sb.AppendLine("if command -v __qc_unload >/dev/null 2>&1; then __qc_unload; fi");
        sb.AppendLine("__qc_unload() {");
        if (commands.Count > 0)
            sb.Append("  unset -f ").AppendJoin(' ', commands.Select(c => c.Name)).AppendLine(" 2>/dev/null");
        sb.AppendLine("  return 0");
        sb.AppendLine("}");
        sb.AppendLine();

        sb.AppendLine("# Auto-reload: before each prompt, reload if the app saved a new version.");
        sb.AppendLine("__qc_autoreload() {");
        sb.AppendLine("  local __qc_rc=$? __qc_stamp=");
        sb.Append("  if [ -n \"$__QC_AUTORELOAD\" ] && { read -r __qc_stamp < ").Append(stampReference)
          .AppendLine("; } 2>/dev/null && [ \"$__qc_stamp\" != \"$__QC_STAMP\" ]; then");
        sb.Append("    . ").AppendLine(selfReference);
        sb.AppendLine("  fi");
        sb.AppendLine("  return $__qc_rc");
        sb.AppendLine("}");
        if (options.AutoReload)
        {
            sb.AppendLine("if [ -n \"${ZSH_VERSION:-}\" ]; then");
            sb.AppendLine("  eval 'if (( ${precmd_functions[(Ie)__qc_autoreload]} == 0 )); then precmd_functions+=(__qc_autoreload); fi'");
            sb.AppendLine("elif [ -n \"${BASH_VERSION:-}\" ]; then");
            sb.AppendLine("  case \"${PROMPT_COMMAND:-}\" in");
            sb.AppendLine("    *__qc_autoreload*) ;;");
            sb.AppendLine("    *) __qc_nl='");
            sb.AppendLine("'");
            sb.AppendLine("       PROMPT_COMMAND=\"__qc_autoreload${PROMPT_COMMAND:+$__qc_nl$PROMPT_COMMAND}\"");
            sb.AppendLine("       unset __qc_nl ;;");
            sb.AppendLine("  esac");
            sb.AppendLine("fi");
        }
        sb.AppendLine();

        for (var i = 0; i < commands.Count; i++)
            AppendCommand(sb, commands[i], i, texts);

        sb.AppendLine("qc() {");
        sb.AppendLine("  case \"$1\" in");
        sb.Append("    reload) . ").Append(selfReference).Append(" && printf '%s\\n' ").Append(Quote(texts.Reloaded)).AppendLine("; return ;;");
        sb.Append("    -a) printf '%s\\n'");
        AppendWords(sb, CommandListing.Lines(all, texts.TitleAll, showLanguage: true, texts));
        sb.AppendLine(" ;;");
        sb.Append("    '') printf '%s\\n'");
        AppendWords(sb, CommandListing.Lines(commands, string.Format(texts.TitleShell, "sh"), showLanguage: false, texts));
        sb.AppendLine(" ;;");
        foreach (var (name, lines) in CommandListing.Details(all, texts))
        {
            sb.Append("    ").Append(name).Append(") printf '%s\\n'");
            AppendWords(sb, lines);
            sb.AppendLine(" ;;");
        }
        sb.Append("    *) printf '%s%s\\n' ").Append(Quote(texts.UnknownCommand)).AppendLine(" \"$1\" >&2; return 1 ;;");
        sb.AppendLine("  esac");
        sb.AppendLine("}");
        return Stamp.Apply(sb.ToString().ReplaceLineEndings("\n"));
    }

    /// <summary>Only the definition of one command – used by "Try it" on top of a normal session.</summary>
    public static string GenerateSingle(QuickCommand command, TerminalTexts texts)
    {
        var sb = new StringBuilder();
        AppendCommand(sb, command, 0, texts);
        return sb.ToString().ReplaceLineEndings("\n");
    }

    private static void AppendCommand(StringBuilder sb, QuickCommand c, int index, TerminalTexts texts)
    {
        var body = c.Script.ReplaceLineEndings("\n").Trim('\n');
        if (body.Trim().Length == 0)
            body = ":";
        if (c.HasParameters)
            body = ParserCode(c, texts) + body;
        var definition = c.Name + "() {\n" + body + "\n}";
        sb.Append("# ").AppendLine(c.Name);
        sb.Append("unalias ").Append(c.Name).AppendLine(" 2>/dev/null");
        sb.Append("eval ").Append(Quote(definition))
          .Append(" || printf '%s\\n' ").Append(Quote(string.Format(texts.CouldNotLoad, c.Name))).AppendLine(" >&2");
        if (c.HasParameters)
            AppendCompletion(sb, c, index);
        sb.AppendLine();
    }

    /// <summary>Parses "$@" into the declared parameters, leaving the remaining arguments in "$@".</summary>
    private static string ParserCode(QuickCommand c, TerminalTexts texts)
    {
        var ps = c.Parameters.Select(p => (P: p, N: ParameterRules.NormalizeName(p.Name))).ToList();
        var sb = new StringBuilder();
        sb.Append("local ").AppendJoin(' ', ps.Select(x => x.N + "=" + (x.P.EffectiveDefault.Length > 0 ? Quote(x.P.EffectiveDefault) : "")))
          .Append('\n');
        sb.Append("local __qc_lit= ").AppendJoin(' ', ps.Select(x => "__qc_s_" + x.N + "=")).Append('\n');
        sb.Append("local -a __qc_rest\n__qc_rest=()\n");
        sb.Append("while [ $# -gt 0 ]; do\n");
        sb.Append("  if [ -n \"$__qc_lit\" ]; then __qc_rest+=(\"$1\"); shift; continue; fi\n");
        sb.Append("  case \"$1\" in\n");
        sb.Append("    --) __qc_lit=1 ;;\n");
        sb.Append("    -h|--help) printf '%s\\n'");
        AppendWords(sb, HelpText.Lines(c, texts, includeLanguage: false));
        sb.Append("; return 0 ;;\n");
        foreach (var (p, n) in ps)
        {
            if (p.Kind == ParameterKind.Switch)
            {
                sb.Append("    --").Append(n).Append("|-").Append(n).Append(") ").Append(n).Append("=1; __qc_s_").Append(n).Append("=1 ;;\n");
                continue;
            }
            sb.Append("    --").Append(n).Append("=*|-").Append(n).Append("=*) ").Append(n).Append("=\"${1#*=}\"; __qc_s_").Append(n).Append("=1 ;;\n");
            sb.Append("    --").Append(n).Append("|-").Append(n).Append(") if [ $# -lt 2 ]; then printf '%s\\n' ")
              .Append(Quote(string.Format(texts.MissingValue, c.Name, n))).Append(" >&2; return 2; fi; ")
              .Append(n).Append("=\"$2\"; __qc_s_").Append(n).Append("=1; shift ;;\n");
        }
        sb.Append("    -[A-Za-z]*|--[A-Za-z]*) __qc_rest+=(\"$1\") ;;\n");
        sb.Append("    *) ");
        var positional = ps.Where(x => x.P.IsPositional).ToList();
        foreach (var (p, n) in positional)
            sb.Append(p == positional[0].P ? "if" : "elif").Append(" [ -z \"$__qc_s_").Append(n).Append("\" ]; then ")
              .Append(n).Append("=\"$1\"; __qc_s_").Append(n).Append("=1; ");
        sb.Append(positional.Count > 0 ? "else __qc_rest+=(\"$1\"); fi ;;\n" : "__qc_rest+=(\"$1\") ;;\n");
        sb.Append("  esac\n");
        sb.Append("  shift\n");
        sb.Append("done\n");

        var usage = Quote("  " + texts.Usage + " " + HelpText.UsageLine(c));
        foreach (var (p, n) in ps.Where(x => x.P.Required && x.P.Kind != ParameterKind.Switch))
            sb.Append("if [ -z \"$__qc_s_").Append(n).Append("\" ]; then printf '%s\\n' ")
              .Append(Quote(string.Format(texts.MissingArgument, c.Name, n))).Append(' ').Append(usage).Append(" >&2; return 2; fi\n");
        foreach (var (p, n) in ps.Where(x => x.P.Kind == ParameterKind.Choice && x.P.Choices.Count > 0))
            sb.Append("if [ -n \"$").Append(n).Append("\" ]; then case \"$").Append(n).Append("\" in ")
              .AppendJoin('|', p.Choices.Select(Quote)).Append(") ;; *) printf '%s\\n' ")
              .Append(Quote(string.Format(texts.InvalidChoice, c.Name, n, string.Join(", ", p.Choices)))).Append(" >&2; return 2 ;; esac; fi\n");
        sb.Append("set -- \"${__qc_rest[@]}\"\n");
        sb.Append("unset __qc_rest __qc_lit ").AppendJoin(' ', ps.Select(x => "__qc_s_" + x.N)).Append('\n');
        return sb.ToString();
    }

    /// <summary>Tab completion for --flags and choice values (bash: complete -F, zsh: compdef if compinit is loaded).</summary>
    private static void AppendCompletion(StringBuilder sb, QuickCommand c, int index)
    {
        var flags = string.Join(' ', c.Parameters.Select(p => "--" + ParameterRules.NormalizeName(p.Name)).Append("--help"));
        var choices = c.Parameters.Where(p => p.Kind == ParameterKind.Choice && p.Choices.Count > 0)
            .Select(p => (N: ParameterRules.NormalizeName(p.Name), Values: string.Join(' ', p.Choices)))
            .ToList();

        var bash = new StringBuilder();
        bash.Append("__qc_c").Append(index).Append("() {\n");
        bash.Append("  local cur=\"${COMP_WORDS[COMP_CWORD]}\" prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n");
        if (choices.Count > 0)
        {
            bash.Append("  case \"$prev\" in\n");
            foreach (var (n, values) in choices)
                bash.Append("    --").Append(n).Append("|-").Append(n).Append(") COMPREPLY=($(compgen -W '").Append(values).Append("' -- \"$cur\")); return 0 ;;\n");
            bash.Append("  esac\n");
        }
        bash.Append("  case \"$cur\" in -*) COMPREPLY=($(compgen -W '").Append(flags).Append("' -- \"$cur\")) ;; esac\n");
        bash.Append("}\n");
        bash.Append("complete -o default -F __qc_c").Append(index).Append(' ').Append(c.Name);

        var zsh = new StringBuilder();
        zsh.Append("__qc_z").Append(index).Append("() {\n");
        if (choices.Count > 0)
        {
            zsh.Append("  case \"${words[CURRENT-1]}\" in\n");
            foreach (var (n, values) in choices)
                zsh.Append("    --").Append(n).Append("|-").Append(n).Append(") compadd -- ").Append(values).Append("; return ;;\n");
            zsh.Append("  esac\n");
        }
        zsh.Append("  if [[ \"$PREFIX\" == -* ]]; then compadd -- ").Append(flags).Append("; else _files; fi\n");
        zsh.Append("}\n");
        zsh.Append("(( $+functions[compdef] )) && compdef __qc_z").Append(index).Append(' ').Append(c.Name);

        sb.Append("if [ -n \"${BASH_VERSION:-}\" ]; then eval ").Append(Quote(bash.ToString()))
          .Append("; elif [ -n \"${ZSH_VERSION:-}\" ]; then eval ").Append(Quote(zsh.ToString())).AppendLine("; fi");
    }

    private static void AppendWords(StringBuilder sb, IEnumerable<string> lines)
    {
        foreach (var line in lines)
            sb.Append(' ').Append(Quote(line));
    }

    /// <summary>Single-quoted sh string: ' becomes '\''.</summary>
    public static string Quote(string value) => "'" + value.Replace("'", "'\\''") + "'";
}

public static class CmdGenerator
{
    public const string FileExtension = ".cmd";

    /// <summary>Second line of every generated file; only files carrying it are ever deleted.</summary>
    public const string Marker = "rem " + CommandListing.GeneratedNotice;

    /// <summary>
    /// cmd reads batch files in the console's OEM code page (e.g. 850), not UTF-8. Writing in it keeps
    /// umlauts in paths and messages intact.
    /// </summary>
    public static Encoding FileEncoding
    {
        get
        {
            try
            {
                Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);
                var codePage = CultureInfo.CurrentCulture.TextInfo.OEMCodePage;
                return codePage == 65001 ? FileUtil.Utf8NoBom : Encoding.GetEncoding(codePage);
            }
            catch (Exception e) when (e is ArgumentException or NotSupportedException)
            {
                return FileUtil.Utf8NoBom;
            }
        }
    }

    /// <summary>
    /// Without parameters there is no setlocal: the batch file runs inside the calling cmd process, so `cd` and
    /// `set` stay in effect after it ends. With parameters the variables are kept local and only the current
    /// directory is carried out.
    /// </summary>
    public static string GenerateCommandFile(QuickCommand command, TerminalTexts? texts = null)
    {
        texts ??= TerminalTexts.English;
        var sb = new StringBuilder();
        void Line(string s) => sb.Append(s).Append("\r\n");

        Line("@echo off");
        Line(Marker);
        var body = command.Script.ReplaceLineEndings("\r\n").TrimEnd('\r', '\n');
        if (!command.HasParameters)
        {
            if (body.Length > 0)
                Line(body);
            return sb.ToString();
        }

        var ps = command.Parameters.Select(p => (P: p, N: ParameterRules.NormalizeName(p.Name))).ToList();
        Line("setlocal EnableExtensions DisableDelayedExpansion");
        foreach (var (p, n) in ps)
        {
            Line("set \"" + n + "=" + p.EffectiveDefault.Replace("%", "%%") + "\"");
            Line("set \"__qc_s_" + n + "=\"");
        }
        Line(":__qc_next");
        Line("if \"%~1\"==\"\" goto __qc_done");
        Line("if /i \"%~1\"==\"-h\" goto __qc_help");
        Line("if /i \"%~1\"==\"--help\" goto __qc_help");
        Line("if \"%~1\"==\"/?\" goto __qc_help");
        foreach (var (_, n) in ps)
        {
            Line("if /i \"%~1\"==\"--" + n + "\" goto __qc_f_" + n);
            Line("if /i \"%~1\"==\"-" + n + "\" goto __qc_f_" + n);
        }
        Line("set \"__qc_a=%~1\"");
        Line("if \"%__qc_a:~0,2%\"==\"--\" goto __qc_skip");
        foreach (var (_, n) in ps.Where(x => x.P.IsPositional))
            Line("if not defined __qc_s_" + n + " goto __qc_p_" + n);
        Line(":__qc_skip");
        Line("shift");
        Line("goto __qc_next");
        foreach (var (p, n) in ps)
        {
            if (p.IsPositional)
            {
                Line(":__qc_p_" + n);
                Line("set \"" + n + "=%~1\"");
                Line("set \"__qc_s_" + n + "=1\"");
                Line("shift");
                Line("goto __qc_next");
            }
            Line(":__qc_f_" + n);
            if (p.Kind == ParameterKind.Switch)
            {
                Line("set \"" + n + "=1\"");
            }
            else
            {
                Line("if \"%~2\"==\"\" goto __qc_e_v_" + n);
                Line("set \"" + n + "=%~2\"");
                Line("shift");
            }
            Line("set \"__qc_s_" + n + "=1\"");
            Line("shift");
            Line("goto __qc_next");
        }

        Line(":__qc_done");
        foreach (var (_, n) in ps.Where(x => x.P.Required && x.P.Kind != ParameterKind.Switch))
            Line("if not defined __qc_s_" + n + " goto __qc_e_m_" + n);
        foreach (var (p, n) in ps.Where(x => x.P.Kind == ParameterKind.Choice && x.P.Choices.Count > 0))
        {
            Line("if not defined " + n + " goto __qc_c_" + n);
            Line("set \"__qc_ok=\"");
            foreach (var choice in p.Choices)
                Line("if /i \"%" + n + "%\"==\"" + choice + "\" set \"__qc_ok=1\"");
            Line("if not defined __qc_ok goto __qc_e_c_" + n);
            Line(":__qc_c_" + n);
        }
        Line("set \"__qc_a=\"");
        Line("set \"__qc_ok=\"");
        foreach (var (_, n) in ps)
            Line("set \"__qc_s_" + n + "=\"");
        // The script runs as a subroutine, so "exit /b" inside it still ends up here and the directory is carried out.
        Line("call :__qc_main %*");
        Line("set \"__qc_rc=%errorlevel%\"");
        Line("endlocal & cd /d \"%CD%\" & exit /b %__qc_rc%");

        Line(":__qc_help");
        foreach (var l in HelpText.Lines(command, texts, includeLanguage: false))
            Line("echo(" + EscapeEcho(l));
        Line("endlocal");
        Line("exit /b 0");
        var usage = "echo(" + EscapeEcho("  " + texts.Usage + " " + HelpText.UsageLine(command)) + " 1>&2";
        foreach (var (p, n) in ps)
        {
            if (p.Kind != ParameterKind.Switch)
            {
                Line(":__qc_e_v_" + n);
                Line("echo(" + EscapeEcho(string.Format(texts.MissingValue, command.Name, n)) + " 1>&2");
                Line("endlocal");
                Line("exit /b 2");
            }
            if (p.Required && p.Kind != ParameterKind.Switch)
            {
                Line(":__qc_e_m_" + n);
                Line("echo(" + EscapeEcho(string.Format(texts.MissingArgument, command.Name, n)) + " 1>&2");
                Line(usage);
                Line("endlocal");
                Line("exit /b 2");
            }
            if (p.Kind == ParameterKind.Choice && p.Choices.Count > 0)
            {
                Line(":__qc_e_c_" + n);
                Line("echo(" + EscapeEcho(string.Format(texts.InvalidChoice, command.Name, n, string.Join(", ", p.Choices))) + " 1>&2");
                Line("endlocal");
                Line("exit /b 2");
            }
        }

        Line(":__qc_main");
        if (body.Length > 0)
            Line(body);
        Line("exit /b");
        return sb.ToString();
    }

    public static string GenerateQcFile(IReadOnlyCollection<QuickCommand> all, TerminalTexts? texts = null)
    {
        texts ??= TerminalTexts.English;
        var commands = all.Where(c => c.Language == ShellLanguage.Cmd).ToList();
        var details = CommandListing.Details(all, texts).ToList();
        var sb = new StringBuilder();
        void Line(string s) => sb.Append(s).Append("\r\n");

        Line("@echo off");
        Line(Marker);
        Line("setlocal EnableExtensions DisableDelayedExpansion");
        Line("if \"%~1\"==\"\" goto __qc_list");
        Line("if /i \"%~1\"==\"reload\" goto __qc_reload");
        Line("if /i \"%~1\"==\"-a\" goto __qc_all");
        for (var i = 0; i < details.Count; i++)
            Line("if /i \"%~1\"==\"" + details[i].Name + "\" goto __qc_d" + i);
        Line("set \"__qc_n=%~1\"");
        Line("setlocal EnableDelayedExpansion");
        Line("echo(" + EscapeEcho(texts.UnknownCommand) + "!__qc_n! 1>&2");
        Line("exit /b 1");
        Line(":__qc_list");
        foreach (var l in CommandListing.Lines(commands, string.Format(texts.TitleShell, "cmd"), showLanguage: false, texts))
            Line("echo(" + EscapeEcho(l));
        Line("exit /b 0");
        Line(":__qc_all");
        foreach (var l in CommandListing.Lines(all, texts.TitleAll, showLanguage: true, texts))
            Line("echo(" + EscapeEcho(l));
        Line("exit /b 0");
        for (var i = 0; i < details.Count; i++)
        {
            Line(":__qc_d" + i);
            foreach (var l in details[i].Lines)
                Line("echo(" + EscapeEcho(l));
            Line("exit /b 0");
        }
        Line(":__qc_reload");
        Line("echo(" + EscapeEcho(texts.CmdReload));
        Line("exit /b 0");
        return sb.ToString();
    }

    /// <summary>Escapes text for `echo(`. Double quotes would switch cmd's escaping off, so they become single quotes.</summary>
    public static string EscapeEcho(string text)
    {
        var sb = new StringBuilder(text.Length);
        foreach (var ch in text)
        {
            switch (ch)
            {
                case '^' or '&' or '|' or '<' or '>':
                    sb.Append('^').Append(ch);
                    break;
                case '%':
                    sb.Append("%%");
                    break;
                case '"':
                    sb.Append('\'');
                    break;
                default:
                    sb.Append(ch);
                    break;
            }
        }
        return sb.ToString();
    }
}

/// <summary>Writes all generated files into ~/.quickcommands. Called after every save and at app start.</summary>
public sealed class OutputWriter(QcPaths paths)
{
    public void WriteAll(IReadOnlyCollection<QuickCommand> commands, GeneratorOptions? options = null)
    {
        options ??= GeneratorOptions.Default;
        Directory.CreateDirectory(paths.OutputDirectory);

        // UTF-8 with BOM: Windows PowerShell 5.1 would read a BOM-less file as ANSI and mangle umlauts.
        // The stamp is written after the script, so a session never sees a new stamp with the old script.
        var ps = PowerShellGenerator.GenerateWithStamp(commands, paths.PowerShellScript, paths.PowerShellStamp, options);
        FileUtil.WriteAtomic(paths.PowerShellScript, ps.Text, FileUtil.Utf8Bom);
        FileUtil.WriteAtomic(paths.PowerShellStamp, ps.Stamp + "\n", FileUtil.Utf8NoBom);

        var sh = ShGenerator.GenerateWithStamp(commands, paths.ShScriptReference, paths.ShStampReference, options);
        FileUtil.WriteAtomic(paths.ShScript, sh.Text, FileUtil.Utf8NoBom);
        FileUtil.WriteAtomic(paths.ShStamp, sh.Stamp + "\n", FileUtil.Utf8NoBom);

        if (OperatingSystem.IsWindows())
            WriteCmdFiles(commands, options.Texts);
    }

    private void WriteCmdFiles(IReadOnlyCollection<QuickCommand> commands, TerminalTexts texts)
    {
        Directory.CreateDirectory(paths.BinDirectory);
        var encoding = CmdGenerator.FileEncoding;
        var expected = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { CommandNameRules.ReservedName + CmdGenerator.FileExtension };

        foreach (var c in commands.Where(c => c.Language == ShellLanguage.Cmd))
        {
            var file = c.Name + CmdGenerator.FileExtension;
            expected.Add(file);
            FileUtil.WriteAtomic(Path.Combine(paths.BinDirectory, file), CmdGenerator.GenerateCommandFile(c, texts), encoding);
        }
        FileUtil.WriteAtomic(Path.Combine(paths.BinDirectory, "qc.cmd"), CmdGenerator.GenerateQcFile(commands, texts), encoding);

        // Remove files of deleted/renamed commands – but only files this tool generated.
        foreach (var file in Directory.EnumerateFiles(paths.BinDirectory, "*" + CmdGenerator.FileExtension))
        {
            if (expected.Contains(Path.GetFileName(file)) || !IsGenerated(file))
                continue;
            File.Delete(file);
        }
    }

    private static bool IsGenerated(string file)
    {
        try
        {
            return File.ReadLines(file).Take(3).Any(l => l.Trim() == CmdGenerator.Marker);
        }
        catch (IOException)
        {
            return false;
        }
    }
}
